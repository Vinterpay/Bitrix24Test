#Задание два
#Дана строка - пароль. Проверьте, соответствует ли пароль требованиям безопасности.
#Если соответствует, выведите уровень надежности (слабый, средний, сильный).
#Если не соответствует - укажите причину.

#Требования:

#Минимум 8 символов, содержит хотя бы одну заглавную букву, содержит хотя бы одну строчную букву, содержит хотя бы одну цифру, содержит хотя бы один спецсимвол (!@#$%^&*)
#Уровни надежности: Слабый: 8-10 символов. Средний: 11-15 символов. Сильный: 16+ символов.
#Пример: Password123! Результат: средний
#Пример: password Результат: не соответствует требованиям (нет заглавных букв, цифр, спецсимволов)

def check_password(password):
    errors = []  # Список для хранения причин несоответствия

    # 1. Проверка требований
    if len(password) < 8:
        errors.append("менее 8 символов")
    if not any(c.isupper() for c in password):
        errors.append("нет заглавных букв")
    if not any(c.islower() for c in password):
        errors.append("нет строчных букв")
    if not any(c.isdigit() for c in password):
        errors.append("нет цифр")
    if not any(c in "!@#$%^&*" for c in password):
        errors.append("нет спецсимволов (!@#$%^&*)")

    # 2. Если есть ошибки, выводим их
    if errors:
        return f"не соответствует требованиям ({', '.join(errors)})"

    # 3. Если ошибок нет, определяем уровень надежности по длине
    length = len(password)
    if length <= 10:
        return "слабый"
    elif length <= 15:
        return "средний"
    else:
        return "сильный"


# Примеры использования:
print(check_password("Password123!"))
# Вывод: средний

print(check_password("password"))
# Вывод: не соответствует требованиям (нет заглавных букв, нет цифр, нет спецсимволов (!@#$%^&*))

print(check_password("Ab1!"))
# Вывод: не соответствует требованиям (менее 8 символов)

print(check_password("SuperStrongPassword123!@#"))
# Вывод: сильный