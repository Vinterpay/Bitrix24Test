def get_boundary_values(a, b):
    # 1. Проверяем, являются ли a и b целыми числами (int)
    if type(a) is not int or type(b) is not int:
        return "Некорректные данные"

    # 2. Проверяем, что левая граница не больше правой
    if a > b:
        return "Некорректный диапазон"

    # 3. Собираем все нужные значения в фигурные скобки {}
    # Фигурные скобки создают "множество" (set).
    # Главная фишка множества: оно САМО удаляет все повторяющиеся числа.
    values = {a - 1, a, a + 1, b - 1, b, b + 1}

    # 4. Функция sorted() берет эти значения, выстраивает их по возрастанию
    # и превращает в обычный список, который мы и возвращаем.
    return sorted(values)


# --- Проверка на примерах ---
print(get_boundary_values(1, 100))
# Вывод: [0, 1, 2, 99, 100, 101]

print(get_boundary_values(5, 5))
# Вывод: [4, 5, 6] (повторы 4, 5, 6 удалились сами)

print(get_boundary_values(100, 1))
# Вывод: Некорректный диапазон

print(get_boundary_values(1.5, 10))
# Вывод: Некорректные данные (потому что 1.5 это дробное число, float)

print(get_boundary_values("5", 10))
# Вывод: Некорректные данные (потому что "5" это строка, str)